/**
 * The four conditions.
 *
 * Each is a few lines, because each *is* only a few lines: a choice of what
 * goes into the prompt. That is the manipulated variable of the study, and
 * confining every condition to this file makes the whole difference between
 * them readable at once.
 *
 * Names match the dissertation's Table A so a reader can line them up:
 *
 *   l0_baseline           Baseline          the first attempt, no recovery
 *   l1_blind_retry        Blind Retry       try again, shown nothing new
 *   l2_reflection         Reflection-only   + its own previous attempt
 *   l2_5_diagnose_revise  Diagnose+Revise   + real evidence of what went wrong
 */

import { buildPrompt } from "./prompt.ts";
import type { Strategy, StrategyContext, StrategyPlan } from "./types.ts";

/** Shared prompt inputs. Identical across conditions by construction. */
function base(ctx: StrategyContext) {
  return {
    repo: ctx.task.repo,
    problemStatement: ctx.task.problemStatement,
    filePath: ctx.filePath,
    fileContent: ctx.fileContent,
  };
}

/**
 * Baseline — the original first attempt.
 *
 * There is no template for it in `original_prompts.json` because the pilot
 * that produced the baseline used the pre-retrofit unified-diff prompt, which
 * the retrofit replaced (D14). Reproducing the baseline would mean reproducing
 * a prompt the study itself abandoned, and the archived baseline results are
 * already the definitive record of it: 12/20 resolved, verified in Docker,
 * regenerated byte-identically by step 3.
 *
 * So L0 declines rather than approximates. The cell records why, which is the
 * difference between a documented boundary and a hole.
 */
export const baseline: Strategy = {
  id: "l0_baseline",
  label: "Baseline",
  needsHistory: false,
  needsEvidence: false,
  async plan(): Promise<StrategyPlan> {
    return {
      runnable: false,
      reason:
        "l0_baseline is replay-only. Its prompt used the pre-retrofit " +
        "unified-diff format the study superseded; the archived results " +
        "(day8_test, 12/20 resolved, test-verified) are the record. Use " +
        "`bun run replay` for baseline numbers.",
    };
  },
};

/**
 * Blind Retry — a fresh attempt with no new information.
 *
 * Worth noting what "blind" means here, because it is easy to misread: the
 * model is not shown its previous attempt at all. The prompt is identical to a
 * first attempt. So this condition measures how much of recovery is explained
 * by sampling variance alone — which is exactly the right control, and
 * stronger than showing the model its failure without telling it why.
 */
export const blindRetry: Strategy = {
  id: "l1_blind_retry",
  label: "Blind Retry",
  needsHistory: false,
  needsEvidence: false,
  async plan(ctx: StrategyContext): Promise<StrategyPlan> {
    const { prompt, sourceFile, sourceSha256 } = await buildPrompt(
      "l1_blind_retry",
      base(ctx),
    );
    return {
      runnable: true,
      prompt,
      promptSource: sourceFile,
      promptSha256: sourceSha256,
    };
  },
};

/**
 * Reflection-only — shown its previous attempt, told it failed, told nothing
 * about why.
 *
 * The prompt asserts the previous attempt "did NOT resolve the issue". For
 * that to be true the cell must actually have a previous attempt, so a missing
 * history is refused rather than filled with a fresh prompt: running L1's
 * prompt and labelling it L2 would collapse the two conditions being compared.
 */
export const reflection: Strategy = {
  id: "l2_reflection",
  label: "Reflection-only",
  needsHistory: true,
  needsEvidence: false,
  async plan(ctx: StrategyContext): Promise<StrategyPlan> {
    const previous = ctx.history.at(-1);
    if (!previous) {
      return {
        runnable: false,
        reason:
          "l2_reflection needs a previous attempt to reflect on; none was " +
          "recorded for this task. Round 1 must run before round 2.",
      };
    }
    const { prompt, sourceFile, sourceSha256 } = await buildPrompt("l2_reflection", {
      ...base(ctx),
      previousAttempt: previous.response,
    });
    return {
      runnable: true,
      prompt,
      promptSource: sourceFile,
      promptSha256: sourceSha256,
    };
  },
};

/**
 * Diagnose+Revise — Reflection-only plus real evidence of the failure.
 *
 * The one condition that can be unrunnable for a reason that is not about the
 * model. Its prompt tells the model it is receiving "the REAL, ACTUAL result
 * of running your previous patch against the real test suite (ground truth,
 * not a guess)". Without Docker (D6) that sentence can only be honoured from
 * the archive, or weakened to git's apply error.
 *
 * `evidence.ts` resolves which, and labels it. This strategy refuses `none`
 * outright: a Diagnose+Revise prompt with an empty evidence block is a
 * Reflection-only prompt that lies to the model about what it contains.
 */
export const diagnoseRevise: Strategy = {
  id: "l2_5_diagnose_revise",
  label: "Diagnose+Revise",
  needsHistory: true,
  needsEvidence: true,
  async plan(ctx: StrategyContext): Promise<StrategyPlan> {
    const previous = ctx.history.at(-1);
    if (!previous) {
      return {
        runnable: false,
        reason:
          "l2_5_diagnose_revise needs a previous attempt to diagnose; none " +
          "was recorded for this task.",
      };
    }
    if (ctx.evidence.source === "none") {
      return {
        runnable: false,
        reason:
          "l2_5_diagnose_revise needs real evidence of the previous failure " +
          "and none is available. Test output requires Docker, which this " +
          "pipeline does not use (D6); an apply error exists only when the " +
          "patch was rejected. Running without evidence would make this " +
          "condition indistinguishable from Reflection-only (D22).",
      };
    }
    const { prompt, sourceFile, sourceSha256 } = await buildPrompt(
      "l2_5_diagnose_revise",
      {
        ...base(ctx),
        previousAttempt: previous.response,
        evidence: ctx.evidence.text,
      },
    );
    return {
      runnable: true,
      prompt,
      promptSource: sourceFile,
      promptSha256: sourceSha256,
    };
  },
};

export const STRATEGIES = {
  l0_baseline: baseline,
  l1_blind_retry: blindRetry,
  l2_reflection: reflection,
  l2_5_diagnose_revise: diagnoseRevise,
} as const;

export type ImplementedStrategyId = keyof typeof STRATEGIES;

export function getStrategy(id: string): Strategy {
  const s = (STRATEGIES as Record<string, Strategy | undefined>)[id];
  if (!s) {
    throw new Error(
      `strategy "${id}" is not implemented. Implemented: ` +
        `${Object.keys(STRATEGIES).join(", ")}. l3_constrained and ` +
        `l4_tool_grounded are declared in core/types.ts and belong to step 8.`,
    );
  }
  return s;
}
